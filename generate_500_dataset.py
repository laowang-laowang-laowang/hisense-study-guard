all_dataset = []
categories = [
    ("POETRY", poetry_data),
    ("MATH", math_data),
    ("ENGLISH", english_data),
    ("ENCYCLOPEDIA", encyclopedia_data),
    ("GEOGRAPHY", geography_data)
]

qid = 1
for cat_name, data_list in categories:
    print(f"分类 {cat_name}: {len(data_list)} 题")
    for item in data_list:
        all_dataset.append({
            "id": f"q_{qid:04d}",
            "category": cat_name,
            "question": item[0],
            "options": item[1],
            "correctIndex": item[2]
        })
        qid += 1

print(f"总计题目: {len(all_dataset)} 道！")

